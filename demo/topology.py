def hospitals() -> list[tuple[str, str, str]]:
    """Each hospital's name, slug and colour, in CYCLES order."""
    return [
        (HOSPITALS[cycle], hospital_slug(HOSPITALS[cycle]), COLOURS[cycle][0])
        for cycle in CYCLES
    ]


def practices() -> list[tuple[str, str, str]]:
    """Each hospital's practice's name, slug and colour, in CYCLES order."""
    return [
        (PRACTICES[cycle], hospital_slug(PRACTICES[cycle]), COLOURS[cycle][1])
        for cycle in CYCLES
    ]


def nhanes_pairs() -> str:
    """nhanes-download's arguments: each hospital and its practice, in CYCLES
    order (demo/nhanes.py)."""
    return ", ".join(
        f"--pair, {cycle}, {hospital_slug(HOSPITALS[cycle])},"
        f' {hospital_slug(PRACTICES[cycle])}, "{PATIENTS[cycle]}"'
        for cycle in CYCLES
    )


PROVIDE = """\
      # Its laboratory director provided the training cohort at start.
      DEMO_PROVIDE: "1"
"""


def register(commands: list[list[str]]) -> str:
    """DEMO_REGISTER's lines (demo/party.py), indented for its block."""
    return "".join(
        "        " + " ".join(shlex.quote(part) for part in command) + "\n"
        for command in commands
    )


def cycle_of(slug: str) -> str:
    """The cycle of the hospital or practice with this folder name."""
    (cycle,) = [
        cycle
        for cycle in CYCLES
        if slug in (hospital_slug(HOSPITALS[cycle]), hospital_slug(PRACTICES[cycle]))
    ]
    return cycle


def known_practices() -> list[list[str]]:
    """Every practice, at each hospital, by its certificate name (its folder name):
    any practice may send a sample to any hospital."""
    return [
        ["add_practice", hospital_slug(PRACTICES[cycle]), PRACTICES[cycle]]
        for cycle in CYCLES
    ]


def laboratories(practice_cycle: str) -> list[list[str]]:
    """Every hospital's laboratory, at a practice; its paired hospital's is its
    primary one, so by default lab orders follow the hospitals' sizes."""
    return [
        [
            "add_laboratory",
            HOSPITALS[cycle],
            f"{hospital_slug(HOSPITALS[cycle])}-messaging:8441",
            *(["--primary"] if cycle == practice_cycle else []),
        ]
        for cycle in CYCLES
    ]


def recipients() -> list[list[str]]:
    """Every hospital, at the startup, by the certificate name it issues it."""
    return [
        ["add_hospital", hospital_slug(HOSPITALS[cycle]), HOSPITALS[cycle]]
        for cycle in CYCLES
    ]


def compose() -> str:
    hospital_slugs = [slug for _, slug, _ in hospitals()]
    practice_slugs = [slug for _, slug, _ in practices()]
    text = GENERATED + HEAD.replace("NHANES_PAIRS", nhanes_pairs())
    text += MIDDLE.replace("STARTUP_REGISTER", register(recipients()))
    for index, (name, slug, colour) in enumerate(hospitals()):
        # The first hospital builds the image the others use as built.
        build = HOSPITAL_BUILD if index == 0 else ""
        text += fill(
            HOSPITAL,
            name=name,
            slug=slug,
            colour=colour,
            build=build,
            provide=PROVIDE if PROVIDED[cycle_of(slug)] else "",
            register=register(known_practices()),
        )
    text += PRACTICE_INTRO
    for index, (name, slug, colour) in enumerate(practices()):
        # The first practice builds the image the others use as built.
        build = PRACTICE_BUILD if index == 0 else ""
        text += fill(
            PRACTICE,
            name=name,
            slug=slug,
            colour=colour,
            build=build,
            register=register(laboratories(cycle_of(slug))),
        )
    text += PROXY
    text += (
        "    networks:\n      [startup-web, " + ", ".join(hospital_slugs) + ",\n       "
    )
    text += ", ".join(practice_slugs) + "]\n\n"
    text += "networks:\n  setup: {}\n  startup: {internal: true}\n  startup-web: {}\n  final-models: {internal: true}\n"
    text += "  model-updates: {internal: true}\n  messaging: {internal: true}\n"
    for slug in hospital_slugs:
        text += f"  {slug}: {{}}\n  {slug}-flower-client-app: {{internal: true}}\n"
    text += "".join(f"  {slug}: {{}}\n" for slug in practice_slugs)
    text += "\n# One per party: `docker compose down -v` deletes them all.\n"
    text += "volumes:\n  startup: {}\n"
    text += "".join(f"  {slug}: {{}}\n" for slug in hospital_slugs + practice_slugs)
    return text


def proxy_conf() -> str:
    hosts = [
        (f"{slug}.localhost", f"{slug}-web:8000;")
        for slug in ["startup"] + [slug for _, slug, _ in hospitals() + practices()]
    ]
    width = max(len(host) for host, _ in hosts) + 2
    routes = "".join(f"        {host:<{width}}{web}\n" for host, web in hosts)
    routes += "        # Any other name reaches no web app.\n"
    routes += f'        {"default":<{width}}"";\n'
    return GENERATED + PROXY_HEAD + routes + PROXY_TAIL


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=HERE)
    out = parser.parse_args().out
    out.mkdir(parents=True, exist_ok=True)
    (out / "compose.yaml").write_text(compose())
    (out / "proxy.conf").write_text(proxy_conf())


if __name__ == "__main__":
    main()
