"""Generate demo/compose.yaml and demo/proxy.conf from demo/demo.toml and the
hospital of each training cycle (HOSPITALS).

    python -m demo.topology            # into demo/
    python -m demo.topology --out DIR  # elsewhere (the staleness test)
"""

import argparse
import shlex
import tomllib
from pathlib import Path
from typing import Any

from ml.dataset import CYCLES

HERE = Path(__file__).resolve().parent
# Each cycle's hospital, named as in the report: large, medium, small.
HOSPITALS = {
    "2005-2006": "UZ Leuven",
    "2015-2016": "Heilig Hart Leuven",
    "2017-2018": "AZ Diest",
}


def hospital_slug(name: str) -> str:
    """A hospital's or practice's folder name under the demo directory (demo/README.md)."""
    return name.lower().replace(" ", "-")


GENERATED = "# Generated by `python -m demo.topology` from demo/demo.toml: edit that.\n"


def by_cycle(declared: dict[str, Any]) -> dict[str, Any]:
    """demo.toml's entry for each hospital, keyed by cycle like HOSPITALS."""
    known = {hospital_slug(name) for name in HOSPITALS.values()}
    if set(declared) != known:
        raise ValueError(
            f"demo.toml declares {sorted(declared)}; training knows {sorted(known)}"
        )
    return {cycle: declared[hospital_slug(HOSPITALS[cycle])] for cycle in CYCLES}


ENTRIES = by_cycle(tomllib.loads((HERE / "demo.toml").read_text())["hospitals"])
# Each hospital's general practitioner's practice, its colour and patients.
PRACTICES: dict[str, str] = {
    cycle: entry["practice"] for cycle, entry in ENTRIES.items()
}
# Patients each practice, and so its hospital's analyser stand-in, seeds.
PATIENTS: dict[str, int] = {
    cycle: entry["patients"] for cycle, entry in ENTRIES.items()
}
# Whether each hospital's laboratory director provided the training cohort at
# start.
PROVIDED: dict[str, bool] = {
    cycle: entry["provided"] for cycle, entry in ENTRIES.items()
}
# Each hospital's Pico colour, and its practice's from the same family.
COLOURS: dict[str, tuple[str, str]] = {
    cycle: (entry["colour"], entry["practice_colour"])
    for cycle, entry in ENTRIES.items()
}


def fill(template: str, **values: str) -> str:
    for key, value in values.items():
        template = template.replace("{" + key + "}", value)
    return template


