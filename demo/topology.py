PRACTICE_BUILD = "    build: {context: .., dockerfile: demo/practice-web.Dockerfile}\n"

PROXY = """\
  # Between the browser and the parties, like the internet: routes each
  # <party>.localhost by its Host header. The only published port.
  proxy:
    image: nginx:1.28-alpine
    user: *user
    depends_on:
      prepare: {condition: service_completed_successfully}
    ports: ["127.0.0.1:${DEMO_HTTP_PORT:-80}:8080"]
    volumes: ["./proxy.conf:/etc/nginx/nginx.conf:ro"]
    healthcheck:
      test: [CMD, nc, -z, 127.0.0.1, "8080"]
      interval: 2s
      retries: 60
"""

PROXY_HEAD = """\
# Routes each <party>.localhost to that party's web app by the Host header:
# plain HTTP, as the demo leaves out the report's TLS.
worker_processes 1;
pid /tmp/nginx.pid;
error_log stderr warn;

events {}

http {
    # Docker's own DNS, asked at request time: a restarted web app is found again.
    resolver 127.0.0.11 valid=10s;
    access_log off;
    # Run as the demo user: every temp folder in /tmp, none in /var/cache.
    client_body_temp_path /tmp/client_body;
    proxy_temp_path /tmp/proxy;
    fastcgi_temp_path /tmp/fastcgi;
    uwsgi_temp_path /tmp/uwsgi;
    scgi_temp_path /tmp/scgi;

    map $host $web_app {
"""

PROXY_TAIL = """\
    }

    server {
        listen 8080;
        if ($web_app = "") {
            return 421;
        }
        location / {
            proxy_pass http://$web_app;
            proxy_set_header Host $host;
        }
    }
}
"""


def hospitals() -> list[tuple[str, str, str]]:
    """Each hospital's name, slug and colour, in CYCLES order."""
    return [
        (HOSPITALS[cycle], hospital_slug(HOSPITALS[cycle]), COLOURS[cycle][0])
        for cycle in CYCLES
    ]


def practices() -> list[tuple[str, str, str]]:
    """Each hospital's practice's name, slug and colour, in CYCLES order."""
    return [
        (PRACTICES[cycle], hospital_slug(PRACTICES[cycle]), COLOURS[cycle][1])
        for cycle in CYCLES
    ]


def compose() -> str:
    hospital_slugs = [slug for _, slug, _ in hospitals()]
    practice_slugs = [slug for _, slug, _ in practices()]
    folders = [("hospitals", slug) for slug in hospital_slugs]
    folders += [("practices", slug) for slug in practice_slugs]
    text = GENERATED + HEAD
    text += "".join(
        f"      - {{type: volume, source: {slug}, target: /demo/{kind}/{slug}}}\n"
        for kind, slug in folders
    )
    text += MIDDLE
    for name, slug, colour in hospitals():
        text += fill(HOSPITAL, name=name, slug=slug, colour=colour)
    text += PRACTICE_INTRO
    for index, (name, slug, colour) in enumerate(practices()):
        # The first practice builds the image the others use as built.
        build = PRACTICE_BUILD if index == 0 else ""
        text += fill(PRACTICE, name=name, slug=slug, colour=colour, build=build)
    text += PROXY
    text += "    networks:\n      [" + ", ".join(hospital_slugs) + ",\n       "
    text += ", ".join(practice_slugs) + "]\n\n"
    text += "networks:\n  setup: {}\n  startup: {internal: true}\n"
    text += "  model-updates: {internal: true}\n  lab-orders: {internal: true}\n"
    for slug in hospital_slugs:
        text += f"  {slug}: {{}}\n  {slug}-flower-client-app: {{internal: true}}\n"
    text += "".join(f"  {slug}: {{}}\n" for slug in practice_slugs)
    text += "\n# One per party: `docker compose down -v` deletes them all.\n"
    text += "volumes:\n  startup: {}\n"
    text += "".join(f"  {slug}: {{}}\n" for slug in hospital_slugs + practice_slugs)
    return text


def proxy_conf() -> str:
    hosts = [
        (f"{slug}.localhost", f"{slug}-web:8000;")
        for _, slug, _ in hospitals() + practices()
    ]
    width = max(len(host) for host, _ in hosts) + 2
    routes = "".join(f"        {host:<{width}}{web}\n" for host, web in hosts)
    routes += "        # Any other name reaches no web app.\n"
    routes += f'        {"default":<{width}}"";\n'
    return GENERATED + PROXY_HEAD + routes + PROXY_TAIL


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=HERE)
    out = parser.parse_args().out
    out.mkdir(parents=True, exist_ok=True)
    (out / "compose.yaml").write_text(compose())
    (out / "proxy.conf").write_text(proxy_conf())


if __name__ == "__main__":
    main()
